"""Generate firmware/fc_core/src/fc_profile_g1.h from the G1 report outputs.

Keeps the gains the firmware flies identical to the gains G1 proved robust. Run after `make g1`
(g1_report.py calls this automatically).
"""

from __future__ import annotations

import json
from pathlib import Path

from model.params import WHOOP_2IN

HERE = Path(__file__).resolve().parent
GAINS_JSON = HERE / "reports" / "g1" / "proposed_gains.json"
HEADER = HERE.parent / "firmware" / "fc_core" / "src" / "fc_profile_g1.h"

# firmware PARAM group per G1 loop name
GROUPS = {"roll_rate": ("pid_rate", "roll"), "pitch_rate": ("pid_rate", "pitch"), "yaw_rate": ("pid_rate", "yaw"),
          "roll": ("pid_attitude", "roll"), "pitch": ("pid_attitude", "pitch"), "yaw": ("pid_attitude", "yaw")}


def c_float(value: float) -> str:
    text = f"{value:.6g}"
    if not any(ch in text for ch in ".e"):
        text += ".0"
    return text + "f"


def gain_rows(gains: dict) -> list[str]:
    rows = []
    for loop, (group, axis) in GROUPS.items():
        for term in ("kp", "ki", "kd"):
            rows.append(f'    {{"{group}", "{axis}_{term}", {c_float(gains[loop][term])}}},')
    return rows


def render(data: dict) -> str:
    if data.get("gate_passed") is not True:
        raise ValueError("refusing to publish firmware gains without a passing G1 report")
    thrust_base = round(WHOOP_2IN.hover_command * 65535)
    planned = data["timing"]
    interim = data["interim_gains_for_stock_timing"]
    return "\n".join([
        "/*",
        " * GENERATED by sim/gen_profile_header.py from sim/reports/g1/proposed_gains.json - do not edit.",
        " * Gains proven robust by gate G1 (sim/reports/g1/README.md).",
        " */",
        "#pragma once",
        "",
        '#include "fc_profile.h"',
        "",
        f"/* Planned timing: {planned['attitude_rate_hz']:.0f} Hz rate loop, {planned['gyro_lpf_hz']:.0f} Hz gyro LPF */",
        "static const fc_param_value_t FC_G1_GAINS_PLANNED[] = {",
        *gain_rows(data["gains"]),
        "};",
        "",
        f"/* Interim: stock {interim['timing']['attitude_rate_hz']:.0f} Hz timing */",
        "static const fc_param_value_t FC_G1_GAINS_INTERIM[] = {",
        *gain_rows(interim["gains"]),
        "};",
        "",
        f"/* Hover throttle of the modeled 2-inch whoop ({WHOOP_2IN.mass * 1000:.0f} g, "
        f"{WHOOP_2IN.thrust_max:.2f} N per motor) */",
        f"#define FC_WHOOP2_THRUST_BASE {thrust_base}",
        "",
    ])


def main() -> None:
    HEADER.write_text(render(json.loads(GAINS_JSON.read_text())))
    print(f"Wrote {HEADER}")


if __name__ == "__main__":
    main()
